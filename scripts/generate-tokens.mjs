#!/usr/bin/env node
// Generates src/styles/tokens.css from the Stitch DESIGN.md front-matter (read-only source)
// plus the approved extensions in src/styles/token-extensions.json.
// Usage: node scripts/generate-tokens.mjs          (write)
//        node scripts/generate-tokens.mjs --check  (exit 1 if the committed file has drifted)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = `${dirname(dirname(fileURLToPath(import.meta.url)))}/`;
const DESIGN_MD = `${root}design-reference/stitch-selected/DESIGN.md`;
const EXTENSIONS = `${root}src/styles/token-extensions.json`;
const OUT = `${root}src/styles/tokens.css`;

/** Parses the small, indentation-based YAML subset used by the DESIGN.md front-matter. */
export function parseFrontMatter(markdown) {
  const match = markdown.match(/^---\n([\s\S]*?)\n---/);
  if (!match) throw new Error('DESIGN.md has no front-matter');
  const result = {};
  const stack = [{ indent: -1, node: result }];
  for (const raw of match[1].split('\n')) {
    if (!raw.trim() || raw.trim().startsWith('#')) continue;
    const indent = raw.length - raw.trimStart().length;
    const line = raw.trim();
    const sep = line.indexOf(':');
    if (sep < 0) throw new Error(`Unexpected front-matter line: ${line}`);
    const key = line.slice(0, sep).trim();
    let value = line.slice(sep + 1).trim();
    while (stack.length > 1 && stack[stack.length - 1].indent >= indent) stack.pop();
    const parent = stack[stack.length - 1].node;
    if (value === '') {
      parent[key] = {};
      stack.push({ indent, node: parent[key] });
    } else {
      if (/^'.*'$/.test(value) || /^".*"$/.test(value)) value = value.slice(1, -1);
      parent[key] = value;
    }
  }
  return result;
}

const FONT_VAR = { Outfit: 'var(--font-outfit)', 'Plus Jakarta Sans': 'var(--font-jakarta)' };

export function buildTokensCss(design, extensions) {
  const lines = [
    '/* GENERATED by scripts/generate-tokens.mjs — do not edit by hand. */',
    '/* Source: design-reference/stitch-selected/DESIGN.md front-matter + src/styles/token-extensions.json */',
    '@theme {',
    '  --color-*: initial;',
    '  --color-white: #ffffff;',
  ];
  for (const [name, hex] of Object.entries(design.colors)) lines.push(`  --color-${name}: ${hex.toLowerCase()};`);
  for (const [name, hex] of Object.entries(extensions.colors)) lines.push(`  --color-${name}: ${hex.toLowerCase()};`);
  lines.push('  --font-headline: var(--font-outfit), ui-sans-serif, system-ui, sans-serif;');
  lines.push('  --font-body: var(--font-jakarta), ui-sans-serif, system-ui, sans-serif;');
  for (const [name, t] of Object.entries(design.typography)) {
    const family = FONT_VAR[t.fontFamily];
    if (!family) throw new Error(`Unknown font family ${t.fontFamily}`);
    lines.push(`  --text-${name}: ${t.fontSize};`);
    lines.push(`  --text-${name}--line-height: ${t.lineHeight};`);
    lines.push(`  --text-${name}--font-weight: ${t.fontWeight};`);
    if (t.letterSpacing) lines.push(`  --text-${name}--letter-spacing: ${t.letterSpacing};`);
  }
  for (const [name, value] of Object.entries(design.rounded)) {
    lines.push(name === 'DEFAULT' ? `  --radius: ${value};` : `  --radius-${name}: ${value};`);
  }
  for (const [name, value] of Object.entries(design.spacing)) lines.push(`  --spacing-${name}: ${value};`);
  lines.push('}', '');
  return lines.join('\n');
}

export function generate() {
  const design = parseFrontMatter(readFileSync(DESIGN_MD, 'utf8'));
  const extensions = JSON.parse(readFileSync(EXTENSIONS, 'utf8'));
  return buildTokensCss(design, extensions);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const css = generate();
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUT, 'utf8');
    if (current !== css) {
      console.error('tokens.css is out of date. Run: node scripts/generate-tokens.mjs');
      process.exit(1);
    }
    console.log('tokens.css matches DESIGN.md and the approved extensions.');
  } else {
    writeFileSync(OUT, css);
    console.log(`Wrote ${OUT}`);
  }
}
